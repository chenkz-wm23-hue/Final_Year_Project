"""Train starter model and export portable coefficients, report and parity cases."""
import csv
import hashlib
import json
from pathlib import Path

import sklearn
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report

ROOT = Path(__file__).resolve().parents[1]

def read(name):
    with (ROOT / 'ml' / name).open(encoding='utf-8', newline='') as file:
        rows = list(csv.DictReader(file))
    return [r['text'] for r in rows], [r['category'] for r in rows]

def main():
    texts, labels = read('training.csv')
    evaluation, expected = read('evaluation.csv')
    assert not set(t.lower() for t in texts) & set(t.lower() for t in evaluation)
    # ASCII token pattern is reproduced exactly by the Dart inference code.
    vectorizer = TfidfVectorizer(token_pattern=r'[a-z][a-z0-9]+')
    matrix = vectorizer.fit_transform(texts)
    classifier = LogisticRegression(C=4.0, max_iter=1000, random_state=42)
    classifier.fit(matrix, labels)
    data = {
        'version': 1,
        'classes': classifier.classes_.tolist(),
        'vocabulary': {word: int(i) for word, i in vectorizer.vocabulary_.items()},
        'idf': vectorizer.idf_.tolist(),
        'weights': classifier.coef_.tolist(),
        'bias': classifier.intercept_.tolist(),
        'threshold': 0.65,
        'margin': 0.20,
    }
    destination = ROOT / 'lib' / 'data' / 'ml'
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'expense_model_data.dart').write_text(
        '// Generated by ml/train.py. Do not edit by hand.\n'
        '// Starter model trained on authored examples, not real customer data.\n'
        "const expenseModelJson = r'''" + json.dumps(data, separators=(',', ':')) + "''';\n",
        encoding='utf-8',
    )
    probabilities = classifier.predict_proba(vectorizer.transform(evaluation))
    report = {
        'training_source': 'Authored synthetic starter examples; no customer data',
        'evaluation_warning': 'Small authored smoke set, not an independent real-world benchmark',
        'sklearn_version': sklearn.__version__,
        'training_rows': len(texts),
        'evaluation_rows': len(evaluation),
        'training_sha256': hashlib.sha256((ROOT / 'ml/training.csv').read_bytes()).hexdigest(),
        'report': classification_report(expected, classifier.predict(vectorizer.transform(evaluation)), output_dict=True, zero_division=0),
        'accepted_at_threshold': int(sum(max(p) >= data['threshold'] for p in probabilities)),
    }
    (ROOT / 'ml/evaluation_report.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    cases = [
        {'text': text, 'probabilities': p.tolist()}
        for text, p in zip(evaluation, probabilities)
    ]
    (ROOT / 'ml/parity_cases.json').write_text(json.dumps(cases, indent=2), encoding='utf-8')
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    main()
